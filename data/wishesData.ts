export function getWishesByOccasion(slug: string): WishItem[] {
  const items = WISHES_VAULT.filter((w) => w.categorySlug === slug);
  if (items.length > 0) return items;

  const hub = OCCASION_HUBS.find((h) => h.slug === slug);
  const genericOccasionName = hub?.name || slug.split("-").map((s) => s.charAt(0).toUpperCase() + s.slice(1)).join(" ");
  const sections = hub ? hub.sections.filter((s) => s.id !== "all") : [{ id: "general", label: "🌟 Best Wishes" }];

  const generated: WishItem[] = [];
  sections.forEach((sec, sIdx) => {
    const defaultTemplates = SECTION_VARIATIONS[sec.id] || SECTION_VARIATIONS.friends;
    // Generate 15 distinct high-quality wishes per section
    for (let i = 1; i <= 15; i++) {
      const template = defaultTemplates[(i - 1) % defaultTemplates.length];
      generated.push({
        id: `${slug}-${sec.id}-${i}`,
        text: `Wishing you a blessed ${genericOccasionName}! ${template}`,
        hindi: `इस पावन ${genericOccasionName} के अवसर पर आपको और आपके परिवार को हार्दिक शुभकामनाएँ एवं ढेरों खुशियाँ! ✨🎉`,
        hinglish: `Is khaas ${genericOccasionName} ke mauqe par aapko aur aapke parivar ko dheron khushiyan aur barkat mile! ✨🎉`,
        occasion: genericOccasionName,
        categorySlug: slug,
        section: sec.id,
        recipient: sec.label.replace(/^[^\w\s]+/, "").trim(),
        likes: 35000 + (sIdx * 15 + i) * 980,
        featured: i === 1,
      });
    }
  });

  return generated;
}
